"""
ChronosMatch Pure-Python Reference Limit Order Book (LOB) Engine
High-fidelity Price-Time Priority (FIFO) matching engine with fixed-point integer arithmetic.
Serves as the deterministic reference implementation and automatic fallback when native Cython is not compiled.
"""

import time
import bisect
from collections import deque
from dataclasses import dataclass
from typing import Dict, List, Optional, Tuple


@dataclass(slots=True)
class Order:
    """Internal lightweight Limit Order Book node."""
    order_id: int
    side: int
    price: int       # Fixed-point integer (e.g., 15025 = $150.25)
    qty: int         # Remaining volume
    timestamp_ns: int


@dataclass(slots=True)
class Trade:
    """Executed trade fill record."""
    trade_id: int
    maker_order_id: int
    taker_order_id: int
    price: int
    qty: int
    timestamp_ns: int


class LimitOrderBook:
    """
    Price-Time Priority (FIFO) Limit Order Book.
    
    Maintains sorted price levels:
    - Bids: Highest price first (descending).
    - Asks: Lowest price first (ascending).
    - At each price level: Strict FIFO order of arrival.
    - O(1) order cancellation via hash map index.
    """

    def __init__(self) -> None:
        # Price level queues: price -> deque of Order
        self.bids: Dict[int, deque[Order]] = {}
        self.asks: Dict[int, deque[Order]] = {}

        # Sorted unique price levels for efficient best bid/ask discovery
        # bid_prices is kept ascending: best bid is bid_prices[-1]
        self.bid_prices: List[int] = []
        # ask_prices is kept ascending: best ask is ask_prices[0]
        self.ask_prices: List[int] = []

        # Order lookup map: order_id -> (Order, side)
        self.orders: Dict[int, Tuple[Order, int]] = {}

        # Trade history & counters
        self.trade_counter: int = 0
        self.trades: List[Trade] = []

        # Engine telemetry
        self.orders_processed: int = 0
        self.trades_executed: int = 0
        self.total_volume: int = 0
        self.total_match_latency_ns: int = 0
        self.min_latency_ns: int = 1 << 62
        self.max_latency_ns: int = 0
        self.latency_samples: List[float] = []  # Samples in microseconds

    def process_order(
        self,
        order_id: int,
        side: int,
        price: int,
        qty: int,
        timestamp_ns: Optional[int] = None,
    ) -> List[Trade]:
        """
        Process an incoming order packet through the matching engine.
        
        :param order_id: 64-bit unique order ID.
        :param side: 1=BUY, 2=SELL, 3=CANCEL.
        :param price: Fixed-point price in cents (e.g. 15025).
        :param qty: Number of shares / contracts.
        :param timestamp_ns: Monotonic nanosecond timestamp.
        :return: List of Trade executions generated by this order.
        """
        start_ns = time.perf_counter_ns()
        if timestamp_ns is None:
            timestamp_ns = time.time_ns()

        self.orders_processed += 1
        executed_trades: List[Trade] = []

        # Side 3: Cancel Order
        if side == 3:  # SIDE_CANCEL
            self.cancel_order(order_id)
            self._record_latency(start_ns)
            return executed_trades

        # Side 1: Buy Order
        if side == 1:  # SIDE_BUY
            remaining_qty = qty
            
            # Cross against lowest asks
            while self.ask_prices and self.ask_prices[0] <= price and remaining_qty > 0:
                best_ask = self.ask_prices[0]
                level_orders = self.asks[best_ask]

                while level_orders and remaining_qty > 0:
                    maker_order = level_orders[0]
                    trade_qty = min(remaining_qty, maker_order.qty)

                    # Execute fill at maker's price
                    self.trade_counter += 1
                    trade = Trade(
                        trade_id=self.trade_counter,
                        maker_order_id=maker_order.order_id,
                        taker_order_id=order_id,
                        price=best_ask,
                        qty=trade_qty,
                        timestamp_ns=timestamp_ns,
                    )
                    executed_trades.append(trade)
                    self.trades.append(trade)
                    self.trades_executed += 1
                    self.total_volume += trade_qty

                    remaining_qty -= trade_qty
                    maker_order.qty -= trade_qty

                    # If maker order fully filled, evict from queue
                    if maker_order.qty == 0:
                        level_orders.popleft()
                        del self.orders[maker_order.order_id]

                # If price level fully depleted, remove level
                if not level_orders:
                    del self.asks[best_ask]
                    self.ask_prices.pop(0)

            # Rest remaining uncrossed volume on the bid book
            if remaining_qty > 0:
                order = Order(
                    order_id=order_id,
                    side=1,
                    price=price,
                    qty=remaining_qty,
                    timestamp_ns=timestamp_ns,
                )
                if price not in self.bids:
                    self.bids[price] = deque()
                    bisect.insort(self.bid_prices, price)
                self.bids[price].append(order)
                self.orders[order_id] = (order, 1)

        # Side 2: Sell Order
        elif side == 2:  # SIDE_SELL
            remaining_qty = qty

            # Cross against highest bids
            while self.bid_prices and self.bid_prices[-1] >= price and remaining_qty > 0:
                best_bid = self.bid_prices[-1]
                level_orders = self.bids[best_bid]

                while level_orders and remaining_qty > 0:
                    maker_order = level_orders[0]
                    trade_qty = min(remaining_qty, maker_order.qty)

                    # Execute fill at maker's price
                    self.trade_counter += 1
                    trade = Trade(
                        trade_id=self.trade_counter,
                        maker_order_id=maker_order.order_id,
                        taker_order_id=order_id,
                        price=best_bid,
                        qty=trade_qty,
                        timestamp_ns=timestamp_ns,
                    )
                    executed_trades.append(trade)
                    self.trades.append(trade)
                    self.trades_executed += 1
                    self.total_volume += trade_qty

                    remaining_qty -= trade_qty
                    maker_order.qty -= trade_qty

                    # If maker order fully filled, evict from queue
                    if maker_order.qty == 0:
                        level_orders.popleft()
                        del self.orders[maker_order.order_id]

                # If price level fully depleted, remove level
                if not level_orders:
                    del self.bids[best_bid]
                    self.bid_prices.pop()

            # Rest remaining uncrossed volume on the ask book
            if remaining_qty > 0:
                order = Order(
                    order_id=order_id,
                    side=2,
                    price=price,
                    qty=remaining_qty,
                    timestamp_ns=timestamp_ns,
                )
                if price not in self.asks:
                    self.asks[price] = deque()
                    bisect.insort(self.ask_prices, price)
                self.asks[price].append(order)
                self.orders[order_id] = (order, 2)

        self._record_latency(start_ns)
        return executed_trades

    def process_shm_batch(self, shm_memoryview, max_orders: int = 1024) -> int:
        """
        Direct zero-copy processing of 32-byte binary order packets from shared memory.
        Parses buffer directly, matches through LOB, and advances consumer read index.
        """
        from .ipc_bus import ORDER_STRUCT, UINT64_STRUCT
        raw_view = memoryview(shm_memoryview)
        cap = UINT64_STRUCT.unpack_from(raw_view, 8)[0]
        w = UINT64_STRUCT.unpack_from(raw_view, 16)[0]
        r = UINT64_STRUCT.unpack_from(raw_view, 24)[0]
        avail = w - r
        if avail <= 0:
            return 0
        count = min(avail, max_orders)
        mask = cap - 1
        for i in range(count):
            slot = (r + i) & mask
            offset = 64 + (slot * 32)
            order_id, side, price, qty, ts = ORDER_STRUCT.unpack_from(raw_view, offset)
            self.process_order(order_id, side, price, qty, ts)
        UINT64_STRUCT.pack_into(raw_view, 24, r + count)
        return count

    def cancel_order(self, order_id: int) -> bool:
        """
        O(1) cancellation of an active limit order.
        
        :param order_id: Unique order ID to cancel.
        :return: True if order was found and cancelled, False otherwise.
        """
        if order_id not in self.orders:
            return False

        order, side = self.orders.pop(order_id)
        price = order.price

        if side == 1:  # Bid
            if price in self.bids:
                queue = self.bids[price]
                try:
                    queue.remove(order)
                except ValueError:
                    pass
                if not queue:
                    del self.bids[price]
                    idx = bisect.bisect_left(self.bid_prices, price)
                    if idx < len(self.bid_prices) and self.bid_prices[idx] == price:
                        self.bid_prices.pop(idx)
        else:  # Ask
            if price in self.asks:
                queue = self.asks[price]
                try:
                    queue.remove(order)
                except ValueError:
                    pass
                if not queue:
                    del self.asks[price]
                    idx = bisect.bisect_left(self.ask_prices, price)
                    if idx < len(self.ask_prices) and self.ask_prices[idx] == price:
                        self.ask_prices.pop(idx)

        return True

    def get_best_bid(self) -> Optional[int]:
        """Highest active buy price in fixed-point cents, or None if book is empty."""
        return self.bid_prices[-1] if self.bid_prices else None

    def get_best_ask(self) -> Optional[int]:
        """Lowest active sell price in fixed-point cents, or None if book is empty."""
        return self.ask_prices[0] if self.ask_prices else None

    def get_spread(self) -> Optional[int]:
        """Bid-Ask spread in ticks/cents, or None if one side is unpopulated."""
        bb = self.get_best_bid()
        ba = self.get_best_ask()
        if bb is not None and ba is not None:
            return ba - bb
        return None

    def get_mid_price(self) -> Optional[float]:
        """Mid-point price in fixed-point cents, or None if book is one-sided."""
        bb = self.get_best_bid()
        ba = self.get_best_ask()
        if bb is not None and ba is not None:
            return (ba + bb) / 2.0
        return None

    def get_depth(self, levels: int = 5) -> Tuple[List[Tuple[int, int]], List[Tuple[int, int]]]:
        """
        Retrieve aggregated depth of book for top N levels.
        
        :param levels: Number of price levels to return per side.
        :return: (bids, asks) where each is [(price, total_qty), ...]
        """
        bid_depth: List[Tuple[int, int]] = []
        for p in reversed(self.bid_prices[-levels:]):
            total_qty = sum(o.qty for o in self.bids[p])
            bid_depth.append((p, total_qty))

        ask_depth: List[Tuple[int, int]] = []
        for p in self.ask_prices[:levels]:
            total_qty = sum(o.qty for o in self.asks[p])
            ask_depth.append((p, total_qty))

        return bid_depth, ask_depth

    def _record_latency(self, start_ns: int) -> None:
        """Record matching engine execution latency."""
        latency_ns = time.perf_counter_ns() - start_ns
        self.total_match_latency_ns += latency_ns
        if latency_ns < self.min_latency_ns:
            self.min_latency_ns = latency_ns
        if latency_ns > self.max_latency_ns:
            self.max_latency_ns = latency_ns

        # Keep reservoir of up to 100,000 samples for percentile calculations
        if len(self.latency_samples) < 100_000:
            self.latency_samples.append(latency_ns / 1_000.0)  # Microseconds

    def get_latency_stats(self) -> Dict[str, float]:
        """
        Compute latency distribution metrics in microseconds (μs).
        """
        if not self.latency_samples:
            return {"min_us": 0.0, "p50_us": 0.0, "p90_us": 0.0, "p95_us": 0.0, "p99_us": 0.0, "max_us": 0.0, "avg_us": 0.0}

        sorted_samples = sorted(self.latency_samples)
        n = len(sorted_samples)

        def pct(p: float) -> float:
            idx = int(p * n)
            return sorted_samples[min(idx, n - 1)]

        return {
            "min_us": sorted_samples[0],
            "p50_us": pct(0.50),
            "p90_us": pct(0.90),
            "p95_us": pct(0.95),
            "p99_us": pct(0.99),
            "p99_9_us": pct(0.999),
            "max_us": sorted_samples[-1],
            "avg_us": (self.total_match_latency_ns / max(1, self.orders_processed)) / 1_000.0,
        }

    def drain_trades(self) -> List[Trade]:
        """Drain and clear the trade history buffer."""
        t = self.trades
        self.trades = []
        return t

    def reset(self) -> None:
        """Reset order book state and telemetry metrics."""
        self.bids.clear()
        self.asks.clear()
        self.bid_prices.clear()
        self.ask_prices.clear()
        self.orders.clear()
        self.trades.clear()
        self.trade_counter = 0
        self.orders_processed = 0
        self.trades_executed = 0
        self.total_volume = 0
        self.total_match_latency_ns = 0
        self.min_latency_ns = 1 << 62
        self.max_latency_ns = 0
        self.latency_samples.clear()
